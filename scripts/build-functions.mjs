// Bundles each app function (functions-src/*.js) into one self-contained file in src/app/functions/.
// HubSpot packages every function as a single file, so shared code in lib/ must be inlined.
// `--check` fails if a committed bundle is out of date (used in CI).
import { build } from 'esbuild';
import { readFileSync, existsSync } from 'node:fs';
const check = process.argv.includes('--check');
const entries = ['stipCalculate', 'stipDealContext', 'stipSaveEstimate'];
const stale = [];
for (const name of entries) {
  const outfile = `src/app/functions/${name}.js`;
  const res = await build({
    entryPoints: [`functions-src/${name}.js`], bundle: true, platform: 'node', format: 'cjs', target: 'node20',
    write: false, legalComments: 'none',
    banner: { js: `// GENERATED by scripts/build-functions.mjs from functions-src/${name}.js. Do not edit here.` },
  });
  const code = res.outputFiles[0].text;
  if (check) { if (!existsSync(outfile) || readFileSync(outfile, 'utf8') !== code) stale.push(outfile); }
  else { (await import('node:fs')).writeFileSync(outfile, code); }
}
if (check && stale.length) { console.error(`Out of date, run npm run build: ${stale.join(', ')}`); process.exit(1); }
console.log(check ? 'Function bundles are up to date' : `Bundled ${entries.length} functions`);
