// Copies shared UI source into each UI extension directory (each one is bundled on its own).
// `--check` fails if a copy is out of date (used in CI).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const check = process.argv.includes('--check');
// shared file -> UI extension directories it is copied into
const copies = { 'RevenueCalculator.tsx': ['src/app/cards', 'src/app/pages'], 'MatrixPricing.tsx': ['src/app/cards'] };
const banner = '// GENERATED by scripts/sync-shared.mjs from shared/. Do not edit here.\n';
let stale = [];
for (const [f, targets] of Object.entries(copies)) {
  const src = banner + readFileSync(`shared/${f}`, 'utf8');
  for (const t of targets) {
    const dest = `${t}/${f}`;
    if (check) { if (!existsSync(dest) || readFileSync(dest, 'utf8') !== src) stale.push(dest); }
    else writeFileSync(dest, src);
  }
}
if (check && stale.length) { console.error(`Out of date, run npm run sync: ${stale.join(', ')}`); process.exit(1); }
console.log(check ? 'Shared UI copies are up to date' : `Synced ${Object.keys(copies).length} shared file(s)`);
